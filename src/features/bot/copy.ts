export const B: Record<BotLang, Dict> = { en, mr };

export const toBotLang = (v: string | null | undefined): BotLang => (v === "mr" ? "mr" : "en");

/** Translate: `t("mr", "found", 3, 25)`. Falls back to English for a missing key. */
export function tr(lang: BotLang, key: string, ...args: any[]): any {
  const v = B[lang][key] ?? B.en[key];
  return typeof v === "function" ? v(...args) : v;
}
